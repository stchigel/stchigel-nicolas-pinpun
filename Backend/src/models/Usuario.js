class Usuario {
    constructor(dni, nombre, apellido, mail, numero, direccion, contrasena) {
        this.dni = dni;
        this.nombre = nombre;
        this.apellido = apellido;
        this.mail = mail;
        this.numero = numero;
        this.direccion = direccion;
        this.contrasena = contrasena;
    }
}

export default Usuario;
